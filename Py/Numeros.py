Numero_1 = int(input("Ingrese el número 1: "));
Numero_2 = int(input("Ingrese el número 2: "));

if (Numero_1 < Numero_2):
    print("El numero ingresado no es válido.");
elif (Numero_1 > Numero_2):
    print("La suma de los números es: ",(Numero_1 + Numero_2));
else:
    print("La multiplicación de los números es: ",(Numero_1 * Numero_2))